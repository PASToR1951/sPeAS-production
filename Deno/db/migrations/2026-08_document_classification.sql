CREATE OR REPLACE FUNCTION public.peas_validate_document_classification_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  target_document_id INTEGER;
BEGIN
  target_document_id := COALESCE(NEW.document_id, OLD.document_id);

  IF EXISTS (
    SELECT 1
    FROM public.document_research_agenda dra
    JOIN public.research_agenda ra ON ra.id = dra.research_agenda_id
    JOIN public.document_topics dt ON dt.document_id = dra.document_id
    JOIN public.topics t ON t.id = dt.topic_id
    WHERE dra.document_id = target_document_id
      AND ra.normalized_name = t.normalized_name
  ) OR EXISTS (
    SELECT 1
    FROM public.document_research_agenda dra
    JOIN public.research_agenda ra ON ra.id = dra.research_agenda_id
    JOIN public.document_keywords dk ON dk.document_id = dra.document_id
    JOIN public.keywords k ON k.id = dk.keyword_id
    WHERE dra.document_id = target_document_id
      AND ra.normalized_name = k.normalized_term
  ) OR EXISTS (
    SELECT 1
    FROM public.document_topics dt
    JOIN public.topics t ON t.id = dt.topic_id
    JOIN public.document_keywords dk ON dk.document_id = dt.document_id
    JOIN public.keywords k ON k.id = dk.keyword_id
    WHERE dt.document_id = target_document_id
      AND t.normalized_name = k.normalized_term
  ) THEN
    RAISE EXCEPTION 'A document cannot reuse the same normalized term across research agenda, topic, and keyword classifications'
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NULL;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'peas_classification_overlap_agenda_trigger') THEN
    CREATE CONSTRAINT TRIGGER peas_classification_overlap_agenda_trigger
      AFTER INSERT OR UPDATE OR DELETE ON public.document_research_agenda
      DEFERRABLE INITIALLY DEFERRED
      FOR EACH ROW EXECUTE FUNCTION public.peas_validate_document_classification_overlap();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'peas_classification_overlap_topic_trigger') THEN
    CREATE CONSTRAINT TRIGGER peas_classification_overlap_topic_trigger
      AFTER INSERT OR UPDATE OR DELETE ON public.document_topics
      DEFERRABLE INITIALLY DEFERRED
      FOR EACH ROW EXECUTE FUNCTION public.peas_validate_document_classification_overlap();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'peas_classification_overlap_keyword_trigger') THEN
    CREATE CONSTRAINT TRIGGER peas_classification_overlap_keyword_trigger
      AFTER INSERT OR UPDATE OR DELETE ON public.document_keywords
      DEFERRABLE INITIALLY DEFERRED
      FOR EACH ROW EXECUTE FUNCTION public.peas_validate_document_classification_overlap();
  END IF;
END;
$$;
