-- PeAS document classification v2
--
-- Research agendas, topics, and keywords have deliberately separate
-- vocabularies and document-association tables.  This migration is additive
-- and idempotent so it can be applied safely to existing installations.

ALTER TABLE public.research_agenda
  ALTER COLUMN name TYPE VARCHAR(255);

ALTER TABLE public.research_agenda
  ADD COLUMN IF NOT EXISTS code VARCHAR(32),
  ADD COLUMN IF NOT EXISTS normalized_name VARCHAR(255),
  ADD COLUMN IF NOT EXISTS description TEXT,
  ADD COLUMN IF NOT EXISTS effective_from DATE,
  ADD COLUMN IF NOT EXISTS effective_to DATE,
  ADD COLUMN IF NOT EXISTS is_official BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS sort_order INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;

UPDATE public.research_agenda
SET normalized_name = LOWER(REGEXP_REPLACE(BTRIM(name), '[[:space:]]+', ' ', 'g'))
WHERE normalized_name IS NULL;

ALTER TABLE public.document_research_agenda
  ADD COLUMN IF NOT EXISTS is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS assigned_by VARCHAR(255);

CREATE UNIQUE INDEX IF NOT EXISTS research_agenda_official_code_uidx
  ON public.research_agenda (code);

CREATE UNIQUE INDEX IF NOT EXISTS research_agenda_official_name_uidx
  ON public.research_agenda (normalized_name)
  WHERE is_official = TRUE;

CREATE INDEX IF NOT EXISTS research_agenda_active_order_idx
  ON public.research_agenda (is_active, sort_order, id);

CREATE UNIQUE INDEX IF NOT EXISTS document_research_agenda_primary_uidx
  ON public.document_research_agenda (document_id)
  WHERE is_primary = TRUE;

CREATE TABLE IF NOT EXISTS public.topics (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  normalized_name VARCHAR(120) NOT NULL,
  description TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  proposed_by VARCHAR(255),
  reviewed_by VARCHAR(255),
  reviewed_at TIMESTAMP WITHOUT TIME ZONE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT topics_status_check CHECK (status IN ('pending', 'approved', 'retired'))
);

CREATE UNIQUE INDEX IF NOT EXISTS topics_normalized_name_uidx
  ON public.topics (normalized_name);

CREATE INDEX IF NOT EXISTS topics_status_name_idx
  ON public.topics (status, normalized_name);

CREATE TABLE IF NOT EXISTS public.document_topics (
  document_id INTEGER NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
  topic_id INTEGER NOT NULL REFERENCES public.topics(id) ON DELETE RESTRICT,
  topic_order INTEGER NOT NULL DEFAULT 1,
  assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  assigned_by VARCHAR(255),
  PRIMARY KEY (document_id, topic_id)
);

CREATE INDEX IF NOT EXISTS document_topics_topic_idx
  ON public.document_topics (topic_id, document_id);

CREATE TABLE IF NOT EXISTS public.keywords (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term VARCHAR(80) NOT NULL,
  normalized_term VARCHAR(80) NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT keywords_term_length_check CHECK (char_length(BTRIM(term)) BETWEEN 2 AND 80)
);

CREATE UNIQUE INDEX IF NOT EXISTS keywords_normalized_term_uidx
  ON public.keywords (normalized_term);

CREATE TABLE IF NOT EXISTS public.document_keywords (
  document_id INTEGER NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
  keyword_id INTEGER NOT NULL REFERENCES public.keywords(id) ON DELETE RESTRICT,
  keyword_order INTEGER NOT NULL DEFAULT 1,
  assigned_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  assigned_by VARCHAR(255),
  PRIMARY KEY (document_id, keyword_id)
);

CREATE INDEX IF NOT EXISTS document_keywords_keyword_idx
  ON public.document_keywords (keyword_id, document_id);

CREATE TABLE IF NOT EXISTS public.classification_migration_review (
  document_id INTEGER NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
  legacy_research_agenda_id INTEGER NOT NULL REFERENCES public.research_agenda(id) ON DELETE RESTRICT,
  legacy_value VARCHAR(255) NOT NULL,
  suggested_type VARCHAR(20),
  decision VARCHAR(20),
  target_id INTEGER,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  reviewed_by VARCHAR(255),
  reviewed_at TIMESTAMP WITHOUT TIME ZONE,
  notes TEXT,
  PRIMARY KEY (document_id, legacy_research_agenda_id),
  CONSTRAINT classification_review_suggested_type_check CHECK (suggested_type IS NULL OR suggested_type IN ('agenda', 'topic', 'keyword', 'discard')),
  CONSTRAINT classification_review_decision_check CHECK (decision IS NULL OR decision IN ('agenda', 'topic', 'keyword', 'discard')),
  CONSTRAINT classification_review_status_check CHECK (status IN ('pending', 'resolved'))
);

CREATE INDEX IF NOT EXISTS classification_review_status_idx
  ON public.classification_migration_review (status, document_id);

